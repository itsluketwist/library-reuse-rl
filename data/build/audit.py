"""Summarise the built datasets into one report per pipeline.

Reports the shape and balance of each split (row counts, per-category, per-source and - for
library-usage - per-phrasing-mode breakdowns, languages) plus reward coverage: the fraction of
rows whose reward has a non-empty reference set to match against. This is the quality snapshot
referenced in data/README.md.

library_usage is the project's main focus, so it gets its own report
(`build/library/docs/REPORT.md`); every other dataset (product_choice, and any future addition)
goes in a second, general report (`build/amplify/docs/REPORT.md`) - splitting the two keeps the
library docs free of sections about datasets that live elsewhere in the repo.

Usage: python data/build/audit.py
"""

from collections import Counter
from pathlib import Path

from llm_cgr import load_jsonl

from data.build.paths import (
    AMPLIFY_REPORT_FILE,
    LIBRARY_REPORT_FILE,
    LIBRARY_USAGE_DIR,
    PRODUCT_CHOICE_DIR,
)


SPLITS = ("train", "val", "test")

# the built datasets to report on, in order
DATASETS = {
    "product_choice": PRODUCT_CHOICE_DIR,
    "library_usage": LIBRARY_USAGE_DIR,
}

# which datasets go in the library_usage report vs the general one (see module docstring)
LIBRARY_REPORT_DATASETS = {"library_usage"}


def _load_split(
    dataset_dir: Path,
) -> dict[str, list[dict]]:
    """Load the train/val/test jsonl files for a dataset directory.

    Returns a {split_name: rows} mapping (missing files load as empty lists).
    """
    out = {}
    for split in SPLITS:
        path = dataset_dir / f"{split}.jsonl"
        out[split] = load_jsonl(str(path)) if path.exists() else []
    return out


def _reference_key(
    row: dict,
) -> str:
    """The row field the reward matches against (allowlist for product choice, else useful_libs).

    Returns the field name.
    """
    return "allowlist" if row.get("task_type") == "product_choice" else "useful_libs"


def _dataset_section(
    name: str,
    splits: dict[str, list[dict]],
) -> str:
    """Build the markdown section for one dataset.

    Returns the section text.
    """
    all_rows = [row for rows in splits.values() for row in rows]
    total = len(all_rows)
    if total == 0:
        return f"## `{name}`\n\n_No rows built._\n"

    counts = {split: len(rows) for split, rows in splits.items()}
    by_category = Counter(row["category_id"] for row in all_rows)
    by_source = Counter(row.get("source", "?") for row in all_rows)
    by_language = Counter(row.get("language", "?") for row in all_rows)
    with_reference = sum(1 for row in all_rows if row.get(_reference_key(row)))

    lines = [f"## `{name}`", ""]
    # the construction version, when the rows carry one (library-usage stamps v1, v2, ...)
    versions = sorted(
        {row["dataset_version"] for row in all_rows if "dataset_version" in row}
    )
    if versions:
        lines.append(f"- **version**: {', '.join(versions)}")
    lines.append(
        f"- **rows**: {total} "
        f"(train {counts['train']}, val {counts['val']}, test {counts['test']})"
    )
    lines.append(f"- **categories**: {len(by_category)}")
    lines.append(
        f"- **reward coverage**: {with_reference}/{total} "
        f"({with_reference / total:.0%}) rows have a non-empty reward reference set"
    )
    lines.append(f"- **languages**: {dict(by_language)}")
    lines.append(f"- **sources**: {dict(by_source)}")
    # library-usage rows carry a phrasing mode (repo context vs bare ask) - report the mix
    if any("phrasing_mode" in row for row in all_rows):
        by_mode = Counter(row.get("phrasing_mode", "?") for row in all_rows)
        lines.append(f"- **phrasing modes**: {dict(by_mode)}")
    # from v3, script rows also record which wording stage they are (template, outline, ...)
    stages = Counter(row["script_stage"] for row in all_rows if row.get("script_stage"))
    if stages:
        lines.append(f"- **script stages**: {dict(stages)}")
    # from v4, function rows record which of their three requests they are (name, ...)
    function_stages = Counter(
        row["function_stage"] for row in all_rows if row.get("function_stage")
    )
    if function_stages:
        lines.append(f"- **function stages**: {dict(function_stages)}")
    lines.append("")
    lines.append("| category | rows |")
    lines.append("| --- | --- |")
    for category, count in sorted(by_category.items()):
        lines.append(f"| {category} | {count} |")
    lines.append("")
    return "\n".join(lines)


def _build_report(
    title: str,
    dataset_names: list[str],
) -> str:
    """Build one report's markdown, covering just `dataset_names`.

    Returns the report markdown.
    """
    sections = [
        f"# {title}",
        "",
        "Generated by `data/build/audit.py`. Rebuild the data with the amplify and library "
        "build scripts first (see data/README.md).",
        "",
    ]
    for name in dataset_names:
        sections.append(_dataset_section(name, _load_split(DATASETS[name])))
    return "\n".join(sections)


def build_library_report() -> str:
    """Build the report covering library_usage, the project's main focus.

    Returns the report markdown.
    """
    names = [name for name in DATASETS if name in LIBRARY_REPORT_DATASETS]
    return _build_report("library_usage dataset report", names)


def build_general_report() -> str:
    """Build the report covering every other built dataset.

    Returns the report markdown.
    """
    names = [name for name in DATASETS if name not in LIBRARY_REPORT_DATASETS]
    return _build_report("Dataset report", names)


def main() -> None:
    """Write the library_usage and general reports to their respective docs/ directories."""
    LIBRARY_REPORT_FILE.write_text(build_library_report())
    print(f"wrote {LIBRARY_REPORT_FILE}")
    AMPLIFY_REPORT_FILE.parent.mkdir(parents=True, exist_ok=True)
    AMPLIFY_REPORT_FILE.write_text(build_general_report())
    print(f"wrote {AMPLIFY_REPORT_FILE}")


if __name__ == "__main__":
    main()
