"""Stage 04: summarise the built library-reuse datasets into train_dataset/REPORT.md.

Reports the shape and balance of each split (row counts, per-category and per-source
breakdowns, languages) plus allowlist coverage - the fraction of rows whose reward has a
non-empty reference set to match against. This is the quality snapshot referenced in
train_dataset/PLAN.md; extend it with the offline verifier-agreement check once the LLM
judge is wired in.

Usage: python train_dataset/pipeline/04_audit.py
"""

from collections import Counter

from src.utils.io import load_jsonl
from train_dataset.common import DATA_DIR, REPORT_FILE


SPLITS = ("train", "val", "test")


def _load_split(
    name: str,
) -> dict[str, list[dict]]:
    """Load the train/val/test jsonl files for a dataset split directory.

    Returns a {split_name: rows} mapping (missing files load as empty lists).
    """
    out = {}
    for split in SPLITS:
        path = DATA_DIR / name / f"{split}.jsonl"
        out[split] = load_jsonl(path) if path.exists() else []
    return out


def _reference_key(
    row: dict,
) -> str:
    """The row field the reward matches against (allowlist for product choice, else useful_libs).

    Returns the field name.
    """
    return "allowlist" if row.get("task_type") == "product_choice" else "useful_libs"


def _dataset_section(
    name: str,
    splits: dict[str, list[dict]],
) -> str:
    """Build the markdown section for one dataset split.

    Returns the section text.
    """
    all_rows = [row for rows in splits.values() for row in rows]
    total = len(all_rows)
    if total == 0:
        return f"## `{name}`\n\n_No rows built._\n"

    counts = {split: len(rows) for split, rows in splits.items()}
    by_category = Counter(row["category_id"] for row in all_rows)
    by_source = Counter(row.get("source", "?") for row in all_rows)
    by_language = Counter(row.get("language", "?") for row in all_rows)
    with_reference = sum(1 for row in all_rows if row.get(_reference_key(row)))

    lines = [f"## `{name}`", ""]
    lines.append(
        f"- **rows**: {total} "
        f"(train {counts['train']}, val {counts['val']}, test {counts['test']})"
    )
    lines.append(f"- **categories**: {len(by_category)}")
    lines.append(
        f"- **allowlist coverage**: {with_reference}/{total} "
        f"({with_reference / total:.0%}) rows have a non-empty reward reference set"
    )
    lines.append(f"- **languages**: {dict(by_language)}")
    lines.append(f"- **sources**: {dict(by_source)}")
    lines.append("")
    lines.append("| category | rows |")
    lines.append("| --- | --- |")
    for category, count in sorted(by_category.items()):
        lines.append(f"| {category} | {count} |")
    lines.append("")
    return "\n".join(lines)


def build_report() -> str:
    """Build the full REPORT.md contents for every built dataset.

    Returns the report markdown.
    """
    sections = [
        "# Library-reuse dataset report",
        "",
        "Generated by `train_dataset/pipeline/04_audit.py`. Rebuild the data with "
        "`03_build_dataset.py` first.",
        "",
    ]
    for name in ("product_choice", "library_usage"):
        sections.append(_dataset_section(name, _load_split(name)))
    return "\n".join(sections)


def main() -> None:
    """Write the dataset report to train_dataset/REPORT.md."""
    REPORT_FILE.write_text(build_report())
    print(f"wrote {REPORT_FILE}")


if __name__ == "__main__":
    main()
